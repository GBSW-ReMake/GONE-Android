class ProfileCardData {
  final String name;
  final String realName;
  final int? grade;
  final int? classNo;
  final int totalMeritPoints;
  final int totalDemeritPoints;
  final int netScore;

  ProfileCardData({
    required this.name,
    required this.realName,
    required this.grade,
    required this.classNo,
    required this.totalMeritPoints,
    required this.totalDemeritPoints,
    required this.netScore,
  });
}
